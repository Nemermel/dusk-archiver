//! CP437/ASCII glyph masks and cell rasterization.
//!
//! Cells `0..127` are reserved for the engine's monospace text layer, matching
//! `dusk::atlas` so existing UI/`Glyph::ch` indexing keeps working. The glyph
//! table below is intentionally byte-for-byte compatible with the engine's
//! built-in font.

/// Uniform atlas cell edge length.
pub const CELL_PX: u32 = 32;
/// Number of reserved ASCII/text cells at the start of the atlas.
pub const ASCII_CELLS: u16 = 128;
/// First cell available to content-defined sprites.
pub const SPRITE_BASE: u16 = ASCII_CELLS;
/// Cell index used as a guaranteed opaque fallback (ASCII DEL).
pub const FALLBACK_SOLID_CELL: u16 = 127;
/// Bytes per RGBA8 frame.
pub const FRAME_BYTES: usize = (CELL_PX * CELL_PX * 4) as usize;

/// Builds a 32x32 RGBA8 frame from an 8x8 1-bit mask, scaling 4x nearest.
#[must_use]
pub fn frame_from_mask8(rows: &[u8; 8]) -> Vec<u8> {
    let mut frame = vec![0_u8; FRAME_BYTES];
    for (y, &bits) in rows.iter().enumerate() {
        for x in 0_u32..8_u32 {
            if bits & (0x80 >> x) != 0 {
                let base_x = x * 4;
                let base_y = u32::try_from(y).unwrap_or(0) * 4;
                for dy in 0..4_u32 {
                    for dx in 0..4_u32 {
                        set_white(&mut frame, base_x + dx, base_y + dy);
                    }
                }
            }
        }
    }
    frame
}

/// Builds a 32x32 RGBA8 frame from a 32x32 1-bit mask.
#[must_use]
pub fn frame_from_mask32(rows: &[u32; 32]) -> Vec<u8> {
    let mut frame = vec![0_u8; FRAME_BYTES];
    for (y, &bits) in rows.iter().enumerate() {
        for x in 0_u32..32_u32 {
            if bits & (0x8000_0000 >> x) != 0 {
                set_white(&mut frame, x, u32::try_from(y).unwrap_or(0));
            }
        }
    }
    frame
}

/// Builds the atlas frame for a reserved ASCII cell.
///
/// Cells `0..31` are blank, `32..126` use the built-in font, and cell `127` is
/// a fully opaque white square (the engine's fallback solid).
#[must_use]
pub fn ascii_frame(code: u8) -> Vec<u8> {
    if code == u8::try_from(FALLBACK_SOLID_CELL).unwrap_or(u8::MAX) {
        vec![0xFF; FRAME_BYTES]
    } else {
        frame_from_mask8(&ascii_glyph_8x8(code))
    }
}

/// Stamps one 32x32 RGBA8 frame into a cell of the atlas pixel buffer.
pub fn stamp_frame(atlas: &mut [u8], atlas_width: u32, atlas_cols: u32, cell: u16, frame: &[u8]) {
    debug_assert_eq!(frame.len(), FRAME_BYTES);
    let cell = u32::from(cell);
    let base_x = (cell % atlas_cols) * CELL_PX;
    let base_y = (cell / atlas_cols) * CELL_PX;
    for row in 0_u32..CELL_PX {
        let src = (row * CELL_PX * 4) as usize;
        let dst = (((base_y + row) * atlas_width + base_x) * 4) as usize;
        let len = (CELL_PX * 4) as usize;
        atlas[dst..dst + len].copy_from_slice(&frame[src..src + len]);
    }
}

fn set_white(frame: &mut [u8], x: u32, y: u32) {
    let idx = ((y * CELL_PX + x) * 4) as usize;
    frame[idx] = 0xFF;
    frame[idx + 1] = 0xFF;
    frame[idx + 2] = 0xFF;
    frame[idx + 3] = 0xFF;
}

