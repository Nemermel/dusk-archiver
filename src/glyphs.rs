#[cfg(test)]
mod tests {
    use super::{
        ascii_frame, frame_from_mask32, frame_from_mask8, stamp_frame, FALLBACK_SOLID_CELL,
        FRAME_BYTES,
    };

    #[test]
    fn frames_are_always_one_cell() {
        assert_eq!(frame_from_mask8(&[0xFF; 8]).len(), FRAME_BYTES);
        assert_eq!(frame_from_mask32(&[0xFFFF_FFFF; 32]).len(), FRAME_BYTES);
        assert_eq!(ascii_frame(b'A').len(), FRAME_BYTES);
    }

    #[test]
    fn ascii_glyph_scales_four_times() {
        let frame = ascii_frame(b'A');
        // 'A' starts with 0x38 = 0011_1000; first lit pixel is x=2, scaled to 8..12.
        let idx = 8_usize * 4;
        assert_eq!(&frame[idx..idx + 4], &[0xFF; 4]);
        let idx_off = 7_usize * 4;
        assert_eq!(&frame[idx_off..idx_off + 4], &[0, 0, 0, 0]);
    }

    #[test]
    fn fallback_cell_is_solid_white() {
        let frame = ascii_frame(u8::try_from(FALLBACK_SOLID_CELL).unwrap());
        assert!(frame.iter().all(|&b| b == 0xFF));
    }

    #[test]
    fn stamping_places_cells_in_row_major_order() {
        let mut atlas = vec![0_u8; (64 * 64 * 4) as usize];
        stamp_frame(&mut atlas, 64, 2, 3, &[0x7F; FRAME_BYTES]);
        // Cell 3 of a 2-column atlas is col 1, row 1.
        let idx = ((32 * 64 + 32) * 4) as usize;
        assert_eq!(atlas[idx], 0x7F);
        let untouched = 0;
        assert_eq!(atlas[untouched], 0);
    }
}
